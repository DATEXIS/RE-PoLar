"""Eval-protocol pilots: does the paper's own `\\boxed{ANSWER}` instruction
(`re_polar/mcts/rewards.py:PAPER_INSTRUCTION`) -- suspected root cause of a real
~55% prompt-template-echo rate found in the RESCUE error analysis (see
`build_error_analysis_from_textlog.py`/`tag_with_llm.py`) -- matter, and does
an alternative do better? Several protocols, growing over the course of the
investigation:

  --protocol drllm
    DR.LLM's exact protocol (chat-wrapped -- the only mode for an instruct
    model, see `re_polar.mcts.rewards.drllm_chat_prompt`'s docstring),
    max_new_tokens=15 (DR.LLM's own data-generation default for DART-Math),
    graded with their actual import `mathruler.grader`. On Qwen3-8B this
    protocol collapses (very low accuracy, the large majority of generations
    never produce a `\\boxed{}` at all within the 15-token budget); on
    Qwen2.5-7B-Instruct (one of the models DR.LLM's own paper validated this
    on, via --model-id) it reaches much higher accuracy with ~100% boxed
    generations -- confirming it's a Qwen3-specific mismatch (narrates
    reasoning despite an explicit "no explanation" instruction), not the
    protocol being tight everywhere.

  --protocol minerva_math
    lm-evaluation-harness's minerva_math task (what most published
    MATH-benchmark papers cite numbers from) -- 4-shot raw completion with
    real worked examples (`re_polar.mcts.rewards.minerva_math_prompt`, never a
    placeholder), stop generation at "Problem:", max_new_tokens=256 (their
    HFLM default). Graded with OUR OWN `EvaluatorMath`, not their
    exact_match/math_verify metric -- prompt+budget are the faithful part,
    not a full metric reproduction like --protocol drllm is.

  --protocol paper_fewshot / --protocol drllm_fewshot
    An ablation, not a reproduction of anything external: does SHOWING
    solved examples fix format compliance on its own, independent of
    minerva_math's ~256-token CoT cost? Same 4 real MATH problems as
    minerva_math's fewshot set, but with ONLY the terse `\\boxed{X}` answer,
    no reasoning -- isolates "fewshot presence" from "CoT-vs-terse", stays at
    our own 50-token MCTS budget instead of minerva's 256. Each variant
    repeats that prompt's OWN existing per-question structure (paper's
    Problem-Start/End/Answer, or DR.LLM's Question/instruction) with a real
    worked answer, rather than inventing a new format. See
    `re_polar.mcts.rewards.paper_fewshot_prompt` / `drllm_fewshot_prompt`.

  --protocol drllm_raw / drllm_chat_prefill / drllm_chat_strict /
  drllm_chat_qwen_deadcode / paper_minimal_fewshot /
  drllm_chat_minimal_fewshot / drllm_chat_minimal_fewshot_prefill
    Follow-on variants isolating individual candidate fixes at DR.LLM's real
    15-token budget, zero-shot (no fewshot): a response-prefill trick
    (`\\boxed{` injected before generation), a one-demonstration minimal
    fewshot (a single trivial "What is 1+1? -> \\boxed{2}" turn, not 4 real
    MATH problems, to isolate near-zero-cost format nudging), and combining
    both winners together. `paper_default` and `paper_minimal_fewshot` are
    the two rows this repo's echo-sweep paper table (`tab:echo-sweep`,
    generated by `generate_echo_sweep_latex_table.py`) is actually built
    from, alongside 4 `drllm*` rows for cross-comparison; the earlier
    protocols above (`drllm`, `minerva_math`, `paper_fewshot`,
    `drllm_fewshot`) were exploratory precursors, kept here since they're
    real runnable protocols, not currently part of the paper table itself.

IDENTITY-path generation only -- no program/rescue comparison, investigates
the BASE PROMPT itself, independent of MCTS.

Data: DART-Math (`re_polar/datasets/dart_math.py`'s `dart_math_v2`-schema
`diff{N}/{split}.json` files, 500/level per split, has query_id).

    python -m analysis.error_analysis.prompt_variant_pilot --protocol drllm \\
        --n-per-difficulty 40 --output drllm_qwen3_8b.jsonl
    python -m analysis.error_analysis.prompt_variant_pilot --protocol drllm \\
        --model-id Qwen/Qwen2.5-7B-Instruct \\
        --n-per-difficulty 40 --output drllm_qwen25_7b.jsonl
    python -m analysis.error_analysis.prompt_variant_pilot --protocol minerva_math \\
        --n-per-difficulty 40 --output minerva_math_qwen3_8b.jsonl
    python -m analysis.error_analysis.prompt_variant_pilot --protocol paper_default \\
        --model qwen3_8b --dataset-dir dart_math_v2 \\
        --splits train val test --full --batch-size 16 \\
        --output full10k_paper_default_qwen3_8b.jsonl

Top-level classify_formatting/select_samples/mathruler_grade/truncate_at_stop
are stdlib-only (mathruler imported lazily) so they're unit-testable without
torch.
"""
